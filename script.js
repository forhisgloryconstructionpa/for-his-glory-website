// ============================================================
// GALLERY SETUP
// ============================================================

const gallery = document.getElementById("gallery");

let visiblePhotos = [...projectPhotos];
let currentPhoto = 0;


// ============================================================
// GET IMAGE PATH
// ============================================================

function getImagePath(photo) {

  /*
    Some of your current pictures are in the main repository.
    The complete photo pack uses category folders.

    We try the main folder first.
    If the picture isn't there, we automatically try
    the organized category folder.
  */

  return photo.file;
}

function getBackupImagePath(photo) {

  return `${photo.folder}${photo.file}`;

}


// ============================================================
// CATEGORY BUTTONS
// ============================================================

function createFilters() {

  if (!gallery) return;

  const filterContainer =
    document.createElement("div");

  filterContainer.className =
    "gallery-filters";

  const categories = [
    "All Projects",
    ...new Set(
      projectPhotos.map(photo => photo.category)
    )
  ];

  categories.forEach((category, index) => {

    const button =
      document.createElement("button");

    button.type = "button";

    button.className =
      "gallery-filter";

    button.textContent =
      category;

    if (index === 0) {
      button.classList.add("active");
    }

    button.addEventListener(
      "click",
      () => {

        document
          .querySelectorAll(".gallery-filter")
          .forEach(btn =>
            btn.classList.remove("active")
          );

        button.classList.add("active");

        if (category === "All Projects") {

          visiblePhotos =
            [...projectPhotos];

        } else {

          visiblePhotos =
            projectPhotos.filter(
              photo =>
                photo.category === category
            );
        }

        renderGallery();
      }
    );

    filterContainer.appendChild(button);
  });

  gallery.parentNode.insertBefore(
    filterContainer,
    gallery
  );
}


// ============================================================
// RENDER GALLERY
// ============================================================

function renderGallery() {

  if (!gallery) return;

  gallery.innerHTML = "";

  visiblePhotos.forEach(
    (photo, index) => {

      const item =
        document.createElement("button");

      item.type = "button";

      item.className =
        "gallery-item";

      const img =
        document.createElement("img");

      img.src =
        getImagePath(photo);

      img.alt =
        `For His Glory Construction & Repairs - ${photo.category}`;

      img.loading = "lazy";


      // If the image isn't in the main folder,
      // try the organized category folder.

      img.onerror = function () {

        if (
          img.dataset.backupTried !== "true"
        ) {

          img.dataset.backupTried =
            "true";

          img.src =
            getBackupImagePath(photo);
        }
      };


      const caption =
        document.createElement("span");

      caption.className =
        "gallery-caption";

      caption.textContent =
        getPhotoTitle(photo.file);


      item.appendChild(img);

      item.appendChild(caption);


      item.addEventListener(
        "click",
        () => {

          openLightbox(index);

        }
      );


      gallery.appendChild(item);
    }
  );
}


// ============================================================
// PHOTO TITLES
// ============================================================

function getPhotoTitle(filename) {

  return filename
    .replace(/\.[^/.]+$/, "")
    .replace(/_/g, " ")
    .replace(/\b\w/g, letter =>
      letter.toUpperCase()
    );
}


// ============================================================
// LIGHTBOX
// ============================================================

function openLightbox(index) {

  currentPhoto = index;

  let lightbox =
    document.getElementById(
      "photo-lightbox"
    );

  if (!lightbox) {

    lightbox =
      document.createElement("div");

    lightbox.id =
      "photo-lightbox";

    lightbox.className =
      "photo-lightbox";

    lightbox.innerHTML = `

      <button
        class="lightbox-close"
        type="button"
        aria-label="Close photo"
      >
        &times;
      </button>

      <button
        class="lightbox-prev"
        type="button"
        aria-label="Previous photo"
      >
        &#10094;
      </button>

      <div class="lightbox-content">

        <img
          class="lightbox-image"
          src=""
          alt=""
        >

        <div
          class="lightbox-title">
        </div>

      </div>

      <button
        class="lightbox-next"
        type="button"
        aria-label="Next photo"
      >
        &#10095;
      </button>

    `;

    document.body.appendChild(
      lightbox
    );


    lightbox
      .querySelector(
        ".lightbox-close"
      )
      .addEventListener(
        "click",
        closeLightbox
      );


    lightbox
      .querySelector(
        ".lightbox-prev"
      )
      .addEventListener(
        "click",
        () => movePhoto(-1)
      );


    lightbox
      .querySelector(
        ".lightbox-next"
      )
      .addEventListener(
        "click",
        () => movePhoto(1)
      );


    lightbox.addEventListener(
      "click",
      event => {

        if (
          event.target === lightbox
        ) {

          closeLightbox();

        }
      }
    );
  }


  showLightboxPhoto();

  lightbox.classList.add("open");

  document.body.style.overflow =
    "hidden";
}


// ============================================================
// SHOW LIGHTBOX PHOTO
// ============================================================

function showLightboxPhoto() {

  const lightbox =
    document.getElementById(
      "photo-lightbox"
    );

  if (!lightbox) return;

  const photo =
    visiblePhotos[currentPhoto];

  if (!photo) return;


  const image =
    lightbox.querySelector(
      ".lightbox-image"
    );

  const title =
    lightbox.querySelector(
      ".lightbox-title"
    );


  image.dataset.backupTried =
    "false";

  image.src =
    getImagePath(photo);

  image.alt =
    `For His Glory Construction & Repairs - ${photo.category}`;


  image.onerror =
    function () {

      if (
        image.dataset.backupTried !==
        "true"
      ) {

        image.dataset.backupTried =
          "true";

        image.src =
          getBackupImagePath(photo);
      }
    };


  title.textContent =
    getPhotoTitle(photo.file);
}


// ============================================================
// NEXT / PREVIOUS PHOTO
// ============================================================

function movePhoto(direction) {

  if (
    !visiblePhotos.length
  ) return;

  currentPhoto =
    (
      currentPhoto +
      direction +
      visiblePhotos.length
    ) %
    visiblePhotos.length;

  showLightboxPhoto();
}


// ============================================================
// CLOSE LIGHTBOX
// ============================================================

function closeLightbox() {

  const lightbox =
    document.getElementById(
      "photo-lightbox"
    );

  if (!lightbox) return;

  lightbox.classList.remove(
    "open"
  );

  document.body.style.overflow =
    "";
}


// ============================================================
// KEYBOARD CONTROLS
// ============================================================

document.addEventListener(
  "keydown",
  event => {

    const lightbox =
      document.getElementById(
        "photo-lightbox"
      );

    if (
      !lightbox ||
      !lightbox.classList.contains(
        "open"
      )
    ) return;


    if (
      event.key === "Escape"
    ) {

      closeLightbox();

    }


    if (
      event.key === "ArrowLeft"
    ) {

      movePhoto(-1);

    }


    if (
      event.key === "ArrowRight"
    ) {

      movePhoto(1);

    }
  }
);


